insert into public.task_lists(nome, brand_id, campanha_id)
select distinct coalesce(nullif(trim(e->>'project'),''),'Operação'), b.id, nullif(e->>'campaignId','')
from public.operacional_estado o
cross join lateral jsonb_array_elements(o.valor) e
join public.brands b on lower(b.nome)=lower(coalesce(e->>'brand',''))
where o.chave='central.tasks.vitor-gutierrez' and o.dono is null
on conflict (brand_id,nome) do nothing;

update public.operacional_estado o
set valor=(
  select coalesce(jsonb_agg(
    case when tl.id is null then e else e || jsonb_build_object('listId',tl.id::text) end
    order by ord
  ),'[]'::jsonb)
  from jsonb_array_elements(o.valor) with ordinality a(e,ord)
  left join public.brands b on lower(b.nome)=lower(coalesce(e->>'brand',''))
  left join public.task_lists tl on tl.brand_id=b.id and tl.nome=coalesce(nullif(trim(e->>'project'),''),'Operação')
)
where o.chave in ('central.tasks.vitor-gutierrez','allianceos.tasks.vitor-gutierrez')
  and o.dono is null and jsonb_typeof(o.valor)='array';

create or replace function app.ao_criar_usuario()
returns trigger language plpgsql security definer
set search_path to 'public','pg_temp'
as $$
declare
  primeiro boolean;
  c public.equipe_convites%rowtype;
begin
  select not exists(select 1 from public.profiles) into primeiro;
  select * into c from public.equipe_convites where email=lower(trim(new.email));
  insert into public.profiles(id,nome,email,foto_url,papel,ativo,area_id,cargo)
  values(
    new.id,
    coalesce(nullif(trim(c.nome),''),nullif(trim(new.raw_user_meta_data->>'nome'),''),nullif(trim(new.raw_user_meta_data->>'full_name'),''),split_part(new.email,'@',1)),
    lower(new.email),
    new.raw_user_meta_data->>'avatar_url',
    case when primeiro then 'admin'::public.papel_usuario when c.email is not null then c.papel else 'membro'::public.papel_usuario end,
    primeiro or c.email is not null,
    c.area_id,
    nullif(trim(c.cargo),'')
  ) on conflict(id) do update set
    nome=excluded.nome,email=excluded.email,papel=excluded.papel,ativo=excluded.ativo,area_id=excluded.area_id,cargo=excluded.cargo;

  if primeiro then
    insert into public.profile_brands(profile_id,brand_id)
    select new.id,b.id from public.brands b where b.ativo on conflict do nothing;
  elsif c.email is not null then
    insert into public.profile_brands(profile_id,brand_id)
    select new.id,b.id from public.brands b
    where b.ativo and (cardinality(c.marcas)=0 or b.id=any(c.marcas))
    on conflict do nothing;
    update public.equipe_convites set aceito_em=coalesce(aceito_em,now()) where email=lower(trim(new.email));
  end if;
  return new;
end
$$;
