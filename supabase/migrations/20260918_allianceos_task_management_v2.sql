create table if not exists public.task_lists (
  id uuid primary key default gen_random_uuid(),
  nome text not null check (length(trim(nome)) between 1 and 200),
  brand_id uuid not null references public.brands(id),
  campanha_id text,
  criado_por uuid references auth.users(id) default auth.uid(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  arquivado_em timestamptz,
  arquivado_por uuid references auth.users(id),
  unique (brand_id, nome)
);

create table if not exists public.legacy_member_links (
  legacy_name text primary key,
  profile_id uuid not null references public.profiles(id),
  migrado_por uuid references auth.users(id) default auth.uid(),
  migrado_em timestamptz not null default now(),
  tarefas_migradas integer not null default 0,
  check (length(trim(legacy_name)) > 0)
);

create table if not exists public.task_action_audit (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references auth.users(id) default auth.uid(),
  origin text not null check (origin in ('interface','mcp')),
  action text not null,
  entity_type text not null,
  entity_id text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id),
  actor_id uuid references auth.users(id) default auth.uid(),
  kind text not null,
  title text not null,
  body text,
  task_id text,
  event_key text,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create unique index if not exists notifications_event_once_idx
