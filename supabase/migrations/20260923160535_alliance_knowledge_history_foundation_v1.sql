  a.actor_id,
  a.origin,
  a.action,
  a.details || jsonb_build_object('actor_snapshot',a.actor_snapshot)
from public.task_action_audit a
on conflict (event_key) do nothing;

create or replace view alliance_data.knowledge_overview
with (security_invoker = true)
as
select
  b.id as brand_id,
  b.nome as brand_name,
  (select count(*) from alliance_data.decisions d where d.brand_id=b.id and d.status<>'archived')::bigint as decisions,
  (select count(*) from alliance_data.learnings l where l.brand_id=b.id and l.status='active')::bigint as active_learnings,
  (select count(*) from alliance_data.documents x where x.brand_id=b.id)::bigint as documents,
  (select count(*) from alliance_data.activity_events e where e.brand_id=b.id)::bigint as events
from public.brands b
where b.ativo;

revoke all on alliance_data.knowledge_overview from public, anon, authenticated;
grant select on alliance_data.knowledge_overview to service_role;
