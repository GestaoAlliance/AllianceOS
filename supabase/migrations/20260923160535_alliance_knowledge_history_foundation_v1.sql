insert into alliance_data.activity_events (
  event_key, brand_id, occurred_at, event_type, entity_type, entity_id,
  actor_id, origin, summary, before_state, after_state, metadata
)
select
  'campaign-version:' || cv.id::text,
  cv.brand_id,
  cv.created_at,
  'campaign_version',
  'campaign',
  cv.campaign_id,
  cv.actor_id,
  cv.origin,
  cv.note,
  cv.previous_snapshot,
  cv.snapshot,
  jsonb_build_object(
    'changed_keys', cv.changed_keys,
    'is_original', cv.is_original,
    'month_ref', cv.month_ref,
    'brand', cv.brand
  )
from public.campaign_versions cv
on conflict (event_key) do nothing;

