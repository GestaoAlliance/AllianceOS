create table if not exists alliance_data.activity_events (
  id bigint generated by default as identity primary key,
  event_key text unique,
  brand_id uuid references public.brands(id),
  occurred_at timestamptz not null default now(),
  event_type text not null,
  entity_type text,
  entity_id text,
  actor_id uuid references auth.users(id),
  origin text not null default 'system',
  summary text,
  before_state jsonb,
  after_state jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists alliance_activity_events_brand_time_idx
  on alliance_data.activity_events(brand_id, occurred_at desc);
create index if not exists alliance_activity_events_entity_idx
  on alliance_data.activity_events(entity_type, entity_id, occurred_at desc);
create index if not exists alliance_activity_events_type_idx
  on alliance_data.activity_events(event_type, occurred_at desc);

create table if not exists alliance_data.decisions (
  id uuid primary key default gen_random_uuid(),
  brand_id uuid references public.brands(id),
  campaign_id text,
  title text not null,
  decision text not null,
  rationale text,
  status text not null default 'active'
    check (status in ('active','reversed','superseded','completed','archived')),
  decided_at timestamptz not null default now(),
  decided_by uuid references auth.users(id),
  expected_outcome text,
  actual_outcome text,
  outcome_checked_at timestamptz,
  source_event_id bigint references alliance_data.activity_events(id),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists alliance_decisions_brand_time_idx
  on alliance_data.decisions(brand_id, decided_at desc);
create index if not exists alliance_decisions_campaign_idx
  on alliance_data.decisions(campaign_id);

create table if not exists alliance_data.learnings (
  id uuid primary key default gen_random_uuid(),
  brand_id uuid references public.brands(id),
  category text,
  title text not null,
  learning text not null,
  status text not null default 'active'
    check (status in ('active','needs_review','superseded','archived')),
  source_type text,
  source_id text,
  evidence jsonb not null default '[]'::jsonb,
  confidence numeric(5,4) check (confidence is null or (confidence >= 0 and confidence <= 1)),
  valid_from timestamptz,
  valid_until timestamptz,
  created_by uuid references auth.users(id),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists alliance_learnings_brand_idx
  on alliance_data.learnings(brand_id, status, created_at desc);
create index if not exists alliance_learnings_source_idx
  on alliance_data.learnings(source_type, source_id);

create table if not exists alliance_data.documents (
  id uuid primary key default gen_random_uuid(),
  brand_id uuid references public.brands(id),
  title text not null,
  document_type text,
  storage_path text,
  external_url text,
  content_hash text,
  extracted_text text,
  source_system text,
  source_id text,
  created_by uuid references auth.users(id),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists alliance_documents_brand_idx
  on alliance_data.documents(brand_id, created_at desc);
create index if not exists alliance_documents_source_idx
  on alliance_data.documents(source_system, source_id);
create index if not exists alliance_documents_hash_idx
  on alliance_data.documents(content_hash);

create table if not exists alliance_data.data_catalog (
  id text primary key,
  domain text not null,
  entity text not null,
  source_schema text not null,
  source_object text not null,
  storage_model text not null
    check (storage_model in ('canonical','mirror','derived','legacy','foundation')),
  brand_scoped boolean not null default true,
  status text not null default 'active'
    check (status in ('active','ready','legacy','planned','deprecated')),
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

